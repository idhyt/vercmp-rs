use std::cmp::Ordering;

use apk_version::compare_apk_versions;

#[test]
fn test_apk_version_compare() {
    for (a, x, b) in TEST_CASES {
        match compare_apk_versions(a, b) {
            Some(actual) => {
                assert_eq!(
                    actual, *x,
                    "Testing failed: expected {} {:?} {}, but got {:?}",
                    a, x, b, actual
                );
                println!("✅: {} {:?} {}", a, x, b);
            }
            None => {
                panic!("Failed to compare {} and {}", a, b,)
            }
        }
    }
}

